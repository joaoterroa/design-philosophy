# Drives the prototype like a person would and checks what it says.
import sys, pathlib
from playwright.sync_api import sync_playwright
app = pathlib.Path(sys.argv[1]).resolve().as_uri()
fails = []
def check(cond, msg):
    print(("ok   " if cond else "FAIL ") + msg)
    if not cond: fails.append(msg)
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/opt/pw-browsers/chromium', args=['--headless=new'])
    pg = b.new_page(viewport={"width": 1100, "height": 760})
    errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto(app + "#on"); pg.wait_for_timeout(300)
    check(pg.locator("#mb-app").get_attribute("aria-label").startswith("Handover: On call, 14 hours"), "menu-bar item has a spoken label")
    pg.get_by_role("button", name="Hand over…").first.click()
    check(pg.locator("h1").inner_text() == "Hand over a shift", "Hand over… opens the sheet")
    pg.fill("#q", "rao"); pg.wait_for_timeout(100)
    names = pg.locator(".person .name").all_inner_texts()
    check(len(names) == 1 and names[0].startswith("Ananya Rao"), "search filters to one person: %s" % names)
    check("overnight" in pg.locator(".person .why").first.inner_text(), "warning reason is shown for Ananya")
    pg.fill("#q", ""); pg.wait_for_timeout(100)
    pg.get_by_role("button", name="4 more: would double up, be up overnight, or away").click()
    check(pg.locator(".person").count() == 8, "disclosure reveals all 8 candidates")
    pg.locator('.person[data-pick="7"]').click(force=True)
    check("disabled" in (pg.locator('[data-act="send"]').get_attribute("disabled") or "disabled") and pg.locator('.person[data-pick="7"]').get_attribute("aria-checked") == "false", "an away person cannot be picked")
    pg.locator('.person[data-pick="1"]').click()
    pg.check('input[value="rest"]', force=True)
    send = pg.locator('[data-act="send"]').inner_text()
    check(send == "Ask Marta · 14 h 13 m", "send button names person and length: %r" % send)
    pg.locator('[data-act="send"]').click()
    txt = pg.locator(".you").inner_text()
    check("Waiting for Marta Sousa" in txt and "until Marta accepts" in txt, "pending names Marta")
    pg.locator('[data-act="sim-accept"]').click()
    txt = pg.locator(".you").inner_text()
    check("You're off call" in txt and "Marta Sousa has" in txt, "accepting the rest makes you off call")
    check("14h" not in pg.locator("#mb-app").inner_text(), "menu bar drops the time once off call")
    pg.goto(app + "#choose"); pg.wait_for_timeout(200)
    pg.keyboard.press("Escape")
    check(pg.locator(".seg").first.is_visible() and pg.locator("h1").count() == 0, "Esc leaves the sheet")
    pg.keyboard.press("Escape")
    check(pg.locator("#pop").is_hidden(), "second Esc closes the panel")
    pg.goto(app + "#offline"); pg.wait_for_timeout(200)
    check(pg.locator('.you [data-act="handover"]').is_disabled(), "Hand over is disabled offline, with a reason")
    pg.get_by_role("button", name="Try again").click()
    check(pg.locator(".notice").count() == 0, "Try again clears the notice")
    # keyboard reaches the row action
    pg.goto(app + "#on"); pg.wait_for_timeout(200)
    pg.locator(".row-action").first.focus(); pg.wait_for_timeout(300)
    check(pg.locator(".row-action").first.evaluate("e => getComputedStyle(e).opacity") == "1", "row action is visible on keyboard focus")
    # reduced motion
    ctx = b.new_context(reduced_motion="reduce"); p2 = ctx.new_page(); p2.goto(app + "#pending"); p2.wait_for_timeout(200)
    check(p2.locator(".pending-dot").evaluate("e => getComputedStyle(e).animationName") == "none", "reduced motion stops the pending pulse")
    check(not errs, "no page errors %s" % errs)
    b.close()
sys.exit(1 if fails else 0)
